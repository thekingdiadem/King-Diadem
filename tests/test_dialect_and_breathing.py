"""ภาษาอีสาน/เหนือ และ "หายใจไม่ได้" "ไม่รู้สึกตัว" "เลือดออกมาก" ที่เคยได้ Risk 0"""
import pytest

from core.kernel_voice import assess
from core.thai_signals import dedialect

URGENT = ["แม่หายใจไม่ได้", "หายใจไม่ได้เลย ช่วยด้วย", "พ่อหายใจไม่ค่อยได้", "พ่อล้มลงไม่รู้สึกตัว", "เลือดออกมาก",
          "โดนมีดฟันเลือดออกมาก", "แม่หายใจบ่ได้", "ป้อหายใจบ่ออก", "พ่อล้มลงบ่ฮู้สึกตัว", "ผัวตีข้อยทุกมื้อ",
          "เปิ้นตีข้า", "อยากต๋าย", "แม่บ่สบายหนัก หายใจบ่ได้", "โดนมีดฟันเลือดออกหลาย"]
CALM = ["งานเยอะจนหายใจไม่ได้", "หายใจไม่ได้ถ้าไม่มีเธอ", "อิ่มจนหายใจไม่ได้", "ไม่รู้สึกตัวเลยว่าเวลาผ่านไป",
        "เขาไม่รู้สึกตัวว่าทำผิด", "ประจำเดือนมาเลือดออกเยอะ", "โดนมีดบาดนิ้ว", "ไปบ่อน้ำ", "บ่ายนี้ไปไหน",
        "ปวดบ่า", "ข้าวผัดอร่อยหลาย", "บ่เป็นหยัง", "กินข้าวบ่"]


@pytest.mark.parametrize("t", URGENT)
def test_urgent_including_dialect(t):
    assert assess(t)["text_risk"] >= 60, t


@pytest.mark.parametrize("t", CALM)
def test_calm_stays_calm(t):
    assert assess(t)["text_risk"] < 60, t


def test_dedialect_keeps_well_and_afternoon():
    assert dedialect("ไปบ่อน้ำตอนบ่าย") == "ไปบ่อน้ำตอนบ่าย"
    assert dedialect("หายใจบ่ออก") == "หายใจไม่ออก"
