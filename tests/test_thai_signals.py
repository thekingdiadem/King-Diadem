"""วลีไทยที่ต้องดูบริบท — ภาษาไทยไม่มีช่องว่าง คำสั้นจึงซ้อนอยู่ในคำอื่นได้"""
import pytest

from core.thai_signals import (NOT_WANT_TO_LIVE, NO_MONEY_ESSENTIAL, DISCOURAGED,
                               BREAKUP, PARTNER, PARENT, DOCTOR)

CASES = [
    # (pattern, ข้อความที่ต้องจับ, ข้อความที่ต้องไม่จับ)
    (NOT_WANT_TO_LIVE,
     ["ไม่อยากอยู่แล้ว", "ไม่อยากอยู่แล้วค่ะ", "ไม่อยากอยู่บนโลกนี้แล้ว", "ไม่อยากอยู่ต่อแล้ว", "เหนื่อยจนไม่อยากอยู่แล้ว"],
     ["ไม่อยากอยู่แล้วที่ทำงานนี้", "ไม่อยากอยู่บ้านคนเดียว", "ไม่อยากอยู่กับเขาแล้ว", "ไม่อยากอยู่ทีมนี้",
      "ไม่อยากอยู่กรุงเทพแล้ว", "ไม่อยากอยู่คนเดียว"]),
    (NO_MONEY_ESSENTIAL,
     ["ไม่มีเงินซื้อข้าว", "ไม่มีเงินจ่ายค่าเช่า", "ไม่มีเงินเลย", "ไม่มีเงินซื้อยาให้ลูก"],
     ["ไม่มีเงินซื้อไอโฟน", "ไม่มีเงินไปเที่ยว", "ไม่มีเงินเติมเกม"]),
    (DISCOURAGED, ["ท้อแท้มาก", "ท้อใจ", "รู้สึกท้อ"], ["ปวดท้อง", "ตั้งท้อง", "ท้องเสีย"]),
    (BREAKUP, ["แฟนบอกเลิก", "เลิกกันแล้ว", "โดนแฟนทิ้ง", "เขาทิ้งฉันไป"], ["เลิกงานแล้วกลับบ้าน", "เลิกเหล้าได้แล้ว", "ทิ้งขยะ"]),
    (PARTNER, ["ทะเลาะกับแฟน", "แฟนไม่ตอบ"], ["เป็นแฟนบอล", "แฟนคลับศิลปิน", "หนังแฟนตาซี"]),
    (PARENT, ["แม่ไม่สบาย", "ทะเลาะกับพ่อ"], ["ไปเที่ยวแม่น้ำ", "แม่ค้าขายดี", "พ่อค้าคนกลาง", "ยิงแม่นมาก"]),
    (DOCTOR, ["ไปหาหมอ", "หมอนัด"], ["หมอกลงหนัก", "ซื้อหมอนใหม่", "ไปดูหมอลำ", "ไปหาหมอดู"]),
]


@pytest.mark.parametrize("pattern,yes,no", CASES, ids=[c[0].pattern[:12] for c in CASES])
def test_pattern(pattern, yes, no):
    for t in yes:
        assert pattern.search(t), f"ต้องจับ: {t}"
    for t in no:
        assert not pattern.search(t), f"ต้องไม่จับ: {t}"
