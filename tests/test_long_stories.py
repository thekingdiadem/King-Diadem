"""เรื่องเล่ายาวที่มีหลายปัญหาซ้อนกัน — ระบบต้องจับแก่นของเรื่อง ไม่ใช่คำแรกที่เจอ"""
import pytest
from core.kernel_voice import assess, compose

S_LOAN_APP = ("หนูอายุ 22 ค่ะ ทำงานโรงงานที่ระยอง ส่งเงินให้แม่ที่ขอนแก่นทุกเดือนเดือนละ 6000 เพราะแม่เลี้ยงหลานสองคนที่พี่สาวทิ้งไว้ "
              "ตอนนี้โรงงานลดโอทีเหลือแต่เงินเดือนเปล่าๆ 11000 ค่าห้อง 2500 หนูเลยไปกู้แอปมา ตอนนี้ทบไปสามแอปแล้ว เขาโทรทวงทุกวันแล้วโทรไปหาหัวหน้าที่โรงงานด้วย "
              "หนูอายมาก ไม่กล้าบอกแม่ เพราะแม่ก็ป่วยเป็นเบาหวาน บางคืนนั่งร้องไห้ไม่รู้จะทำไงต่อ")
S_FARMER = ("ผมเป็นเกษตรกรปลูกข้าวที่สุพรรณ อายุ 48 ปีนี้น้ำท่วมนาเสียหายหมด หนี้ ธกส. ยังค้างอยู่สองแสน หนี้นอกระบบอีกแปดหมื่นดอกร้อยละ 20 ต่อเดือน "
            "ลูกชายเรียนมหาลัยปีสามต้องจ่ายค่าเทอม เมียบอกให้ขายที่ แต่ที่นาเป็นของพ่อแม่ทิ้งไว้ ผมไม่อยากขาย ช่วงนี้กินเหล้าหนักขึ้นทุกคืน นอนไม่ค่อยหลับ")
S_LGBT = ("ผมอายุ 16 เป็นเกย์ครับ เพื่อนในห้องรู้แล้วก็ล้อทุกวัน มีคนเอารูปผมไปตัดต่อลงกลุ่มไลน์ห้อง ครูก็ไม่ช่วย บอกว่าเด็กแกล้งกันเล่น "
          "ที่บ้านพ่อเป็นทหาร เคยพูดว่าถ้าลูกเป็นตุ๊ดจะไล่ออกจากบ้าน ผมเลยไม่กล้าบอกใคร ช่วงนี้ไม่อยากไปโรงเรียน นอนทั้งวัน เกรดตกหมด")
S_SHOP = ("ผมเปิดร้านอาหารมาสองปี ลงทุนไปหนึ่งล้านสองจากเงินกู้บ้านกับเงินเก็บทั้งหมด ช่วงแรกขายดี แต่ตอนนี้ยอดตกเหลือวันละไม่ถึงสามพัน ค่าเช่าเดือนละสี่หมื่น "
          "ลูกน้องสามคนยังต้องจ่าย เมียบอกให้ปิดร้าน แต่ผมรู้สึกว่าถ้าปิดคือยอมแพ้ ทุกคนที่บ้านจะมองว่าผมล้มเหลว ช่วงนี้ปวดหัวทุกวัน ความดันขึ้น หมอให้ยามาแต่ก็ลืมกินบ่อย")
S_NURSE = ("หนูเรียนพยาบาลปีสี่ค่ะ ฝึกงานหนักมาก ขึ้นเวรดึกติดกันหลายวัน อาจารย์พี่เลี้ยงดุต่อหน้าคนไข้บ่อย หนูรู้สึกว่าไม่ได้อยากเป็นพยาบาลตั้งแต่แรก "
           "ที่บ้านอยากให้เรียน เพราะพ่อบอกว่ามีงานแน่นอน ตอนนี้กินข้าวไม่ลง ใจสั่นก่อนขึ้นเวรทุกครั้ง เมื่อคืนคิดว่าถ้าหายไปเลยคงดีกว่า แต่ไม่ได้คิดจะทำอะไรนะคะ แค่เหนื่อยมาก")


@pytest.mark.parametrize("story,must,must_not", [
    (S_LOAN_APP, "แอปเงินกู้", "HbA1c"),
    (S_FARMER, "หนี้นอกระบบ", "ขึ้นที่สูง"),
    (S_LGBT, "การเป็นตัวเองไม่ใช่ความผิด", "สอบตก"),
    (S_SHOP, "ปิดร้านหรือไปต่อ", "วัดความดันที่บ้าน"),
])
def test_story_core_is_found(story, must, must_not):
    o = compose(story, footer=False)
    assert must in o and must_not not in o, o[:200]


def test_passive_wish_to_disappear_gets_gentle_check():
    a = assess(S_NURSE)
    assert "warning" in a["topics"] and "1323" in compose(S_NURSE, footer=False)


@pytest.mark.parametrize("q", ["ฝนหายไปเลยคงดีกว่า", "ปัญหาหายไปเลยคงดี", "ถ้าหายไปเที่ยวทะเลสักอาทิตย์คงดี"])
def test_disappear_about_other_things_is_not_warning(q):
    assert "warning" not in assess(q)["topics"]


def test_farmer_not_child_poisoning():
    """ "ปลูก" มี "ลูก" · "อยากขาย" มี "ยา" · "ยอม" มี "อม" — เคยถูกอ่านเป็นเด็กกินยา"""
    assert not {"overdose", "swallowed"} & set(assess(S_FARMER)["topics"])
    assert "overdose" in assess("ลูกกินยาพาราไปทั้งแผง")["topics"]


def test_active_flood_still_urgent():
    assert assess("น้ำกำลังท่วม ติดอยู่บนหลังคา")["risk_shown"] >= 60


def test_budget_counts_money_sent_home():
    from core.engine_bridge import _budget
    assert _budget(S_LOAN_APP)["data"]["left"] == 2500


def test_open_shop_is_not_close_shop():
    assert "ปิดร้านหรือไปต่อ" not in compose("อยากเปิดร้านกาแฟ มีเงิน 300,000", footer=False)
