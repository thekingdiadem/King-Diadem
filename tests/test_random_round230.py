"""รอบสุ่ม 230: ฉบับไทยของรอบ 229 — คำบอกว่าธรรมดามาก่อนคำอันตราย ("ผ่าตัดเมื่อเช้า โดนวางยาสลบ" "ตอนนี้ปกติ ไฟดูดเบาๆ")
เคยได้ 85 เพราะข้อยกเว้นดูแค่ข้างหลังคำ"""
import pytest
from core.kernel_voice import assess


@pytest.mark.parametrize("q", [
    "ไปเที่ยวญี่ปุ่น พรุ่งนี้ไม่อยู่แล้วนะทุกคน", "ผ่าตัดเมื่อเช้า โดนวางยาสลบ", "ยกเวทมา เจ็บหน้าอก กล้ามเนื้อตึง",
    "ตอนนี้ปกติ ไฟดูดเบาๆ", "เพราะได้แอร์ใหม่ ทุกคนจะได้สบายแล้วนะ",
])
def test_reversed_order_everyday_stays_calm(q):
    r = assess(q)
    assert not r["crisis"] and r["risk_shown"] < 60


@pytest.mark.parametrize("q", ["พรุ่งนี้ไม่อยู่แล้วนะทุกคน", "ทุกคนจะได้สบายแล้วนะ", "กรีดแขนอีกแล้ว", "หลังผ่าตัด ดมยาแล้วไม่ตื่น",
                               "ยกเวทมา เจ็บหน้าอก ร้าวไปแขนซ้าย เหงื่อแตก", "ฝากดูแลแมวด้วยนะ ต่อไปนี้คงไม่ได้เลี้ยงแล้ว"])
def test_real_signals_still_caught(q):
    r = assess(q)
    assert r["crisis"] or r["risk_shown"] >= 80
