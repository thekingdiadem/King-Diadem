"""เทสต์สุ่มรอบ 16: ภาษาถิ่น (อีสาน เหนือ ใต้) + ติดอยู่ในกองไฟ"""
import pytest
from core.kernel_voice import assess


@pytest.mark.parametrize("q", ["บ่อยากอยู่แล้ว เมื่อยหลาย", "แม่ล้มลงบ่หายใจ", "ผัวมันตีข่อยทุกมื้อ", "บ่อยากเป็นภาระไผแล้ว",
                               "เฮือนไฟไหม้ ออกบ่ได้", "บ่อยากอยู่แล้วเจ้า", "ผัวตี๋ข้าเจ้าทุกวัน", "อยากต๋ายแล้ว",
                               "ไม่อยากอยู่แล้วหนิ", "ผัวมันตีฉานทุกวัน", "บ้านไฟไหม้ ออกไม่ได้", "ติดอยู่ในห้อง ไฟไหม้ชั้นล่าง"])
def test_dialect_and_trapped_fire_heard(q):
    assert assess(q)["risk_shown"] >= 65


@pytest.mark.parametrize("q", ["มื้อนี้กินข้าวหลายคักเด้อ", "บ่อยากไปเฮ็ดงานมื้อนี้ ขี้คร้าน", "ม่วนหลายเจ้า", "หรอยจังหู",
                               "ไผมาหา", "อาตี๋ร้านข้าวมันไก่", "เมื่อวานข่าวไฟไหม้ตลาด"])
def test_everyday_dialect_stays_calm(q):
    assert assess(q)["risk_shown"] < 60
