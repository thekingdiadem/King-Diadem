def _caught(a):
    return a["crisis"] or a["text_risk"] >= 50 or bool(a.get("scam")) or bool(a.get("disaster")) or bool(a.get("intl_urgent"))


@pytest.mark.parametrize("t", REAL)
def test_cjk_emergency_caught_with_thai_number(t):
    assert _caught(assess(t)), t
    out = compose(t)
    assert any(n in out for n in ("1669", "191", "1323", "1155")), (t, out[:120])


@pytest.mark.parametrize("t", BENIGN)
def test_cjk_everyday_is_calm(t):
    a = assess(t)
    assert not a["crisis"] and not (a["text_risk"] >= 50 or a.get("intl_urgent")), t


