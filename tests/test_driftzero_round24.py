"""DriftZero รอบสุ่ม 24: เรื่องดิจิทัล · และคำว่า "เปิด" ที่มี "ปิด" ซ่อนอยู่ · K12 ที่หยุดแผนป้องกันไฟไหม้"""
import pytest
from ENGINE.driftzero import audit


def _stops(a):
    return [g["id"] for g in a["gates"] if g["status"] == "stop"]


@pytest.mark.parametrize("t,gate", [("แอปจะเก็บข้อมูลเด็กอายุต่ำกว่า 13 ปีโดยไม่ขอผู้ปกครอง", "S2"),
                                    ("เกมจะขายกล่องสุ่มให้เด็กโดยไม่จำกัดวงเงิน", "G1"),
                                    ("we'll make the unsubscribe button tiny and grey so fewer people leave", "G1"),
                                    ("จะปิดการแจ้งเตือนช่องโหว่เพราะดังบ่อย", "S1"),
                                    ("โรงงานจะปิดพัดลมระบายอากาศเพื่อลดค่าไฟ", "P1"),
                                    ("เกิดไฟไหม้ในโกดังเมื่อเช้า จะเปิดสายพานต่อเลย", "K12")])
def test_harm_stops(t, gate):
    assert gate in _stops(audit(t))


@pytest.mark.parametrize("t", ["แอปจะให้ผู้ปกครองยืนยันก่อนเด็กซื้อของในเกม", "we'll hash passwords with bcrypt",
                               "จะเปิดการแจ้งเตือนความปลอดภัยทุกระบบ", "จะเปิดพัดลมระบายอากาศทั้งวัน",
                               "บ้านพักคนชราจะเปิดแอร์ตลอดช่วงหน้าร้อน", "จะเปิดระบบเตือนภัยไฟไหม้ทุกชั้น",
                               "จะซื้อประกันไฟไหม้ให้โรงงาน", "จะซ้อมหนีไฟไหม้ทุกไตรมาส", "จะตรวจการปนเปื้อนในน้ำทุกเดือน"])
def test_turning_safety_on_is_not_stopped(t):
    # "เปิด" มี "ปิด" ซ่อนอยู่ — เคยทำให้ "จะเปิดการแจ้งเตือนความปลอดภัย" โดนหยุด
    assert not _stops(audit(t))
