"""บทพูดมิจฉาชีพไทยที่เคยได้ Risk 0 — ต้องขึ้นเตือนมิจฉาชีพ ส่วนเรื่องธรรมดาต้องสงบ"""
import pytest

from core.kernel_voice import assess

SCAM = ["ขอรหัส OTP ที่ส่งไปทางมือถือ", "ชวนลงทุนคริปโตกำไรวันละ 10%", "บอกว่ากรมที่ดินให้ติดตั้งแอปอัปเดตข้อมูล",
        "บอกว่าบัตรเครดิตเราถูกใช้ผิดปกติ ขอเลขหลังบัตร", "ให้กู้เงินด่วน แต่ต้องโอนค่าธรรมเนียมก่อน", "ให้สแกนหน้าในแอปที่ส่งมา",
        "ให้เปิดแอปควบคุมหน้าจอเพื่อช่วยแก้ปัญหา", "ส่งลิงก์ให้ลงทะเบียนรับเงินดิจิทัล", "บอกว่าถูกรางวัล ต้องจ่ายภาษีก่อนรับ",
        "บอกว่ามีพัสดุผิดกฎหมายส่งในชื่อเรา", "บอกว่าเป็นธนาคาร ให้ย้ายเงินไปบัญชีใหม่", "อ้างเป็นลูกโทรมาบอกว่าโดนจับ ต้องโอนค่าประกันตัว",
        "ขายของออนไลน์ โอนแล้วไม่ส่งของ", "แฟนที่คุยในเน็ตขอยืมเงินค่าตั๋วเครื่องบิน"]
CALM = ["ธนาคารส่ง OTP มาตอนโอนเงินเอง ปกติไหม", "สมัครแอปธนาคาร ต้องสแกนหน้าในแอปไหม", "ไปธนาคารย้ายเงินไปบัญชีใหม่ที่เปิดเอง",
        "ใช้ teamviewer ทำงานที่บ้าน", "ถูกรางวัลสลากต้องเสียภาษีไหม", "ลูกค้าโอนแล้ว ร้านออนไลน์เราส่งของพรุ่งนี้"]


@pytest.mark.parametrize("t", SCAM)
def test_scam_script_is_flagged(t):
    a = assess(t)
    assert a["text_risk"] >= 60 and a.get("scam"), (t, a["text_risk"], a.get("scam"))


@pytest.mark.parametrize("t", CALM)
def test_ordinary_money_talk_stays_calm(t):
    assert assess(t)["text_risk"] < 60, t
