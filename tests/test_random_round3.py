"""เทสต์สุ่มรอบ 3 (พ.ย. 2569): หัวข้อที่เคยได้คำตอบทั่วไปหรือผิดเรื่อง"""
import pytest
from core.kernel_voice import assess, compose

GEN = ("ขอเรียงเรื่องนี้ให้เห็นเป็นขั้นก่อน", "Let's lay this out step by step.")


@pytest.mark.parametrize("q,must", [
    ("กินแล้วอ้วก ทำตัวเองให้อ้วก กลัวอ้วน", "1323"),
    ("แมวฉี่ไม่ออก นั่งเบ่ง", "ท่อปัสสาวะอุดตัน"),
    ("หมาที่บ้านไม่ยอมกินข้าวมา 2 วัน", "สัตวแพทย์"),
    ("ลูกโดนเพื่อนที่โรงเรียนแกล้งทุกวัน", "ไม่ใช่ความผิดของเขา"),
    ("บัตรเครดิตโดนรูดโดยไม่รู้ตัว", "อายัดบัตร"),
    ("นอนกรนเสียงดัง ตื่นมาเหนื่อย", "หยุดหายใจขณะหลับ"),
    ("เจอลูกนกตกจากรัง", "หัดบิน"),
    ("อยากรับเลี้ยงหมาจรจัด", "พิษสุนัขบ้า"),
    ("โดนตำรวจเรียกตรวจ ไม่มีใบขับขี่", "DLT QR Licence"),
    ("คริปโตลดไป 70% ควรขายหรือถือ", "ถ้าวันนี้มีเงินสด"),
    ("ทำงานที่บ้านแล้วแยกเวลางานกับชีวิตไม่ออก", "เวลาเลิกงาน"),
    ("เจ้านายส่งไลน์มาตอนตีสองให้ตอบทันที", "เวลาเลิกงาน"),
    ("ถูกเพื่อนสนิทหักหลัง", "ความไว้ใจ"),
    ("ลืมพาสปอร์ตไว้ที่โรงแรม เครื่องบินออกพรุ่งนี้", "โรงแรม"),
    ("เป็นแม่เลี้ยงเดี่ยว เหนื่อยมาก", "ค่าเลี้ยงดูบุตร"),
    ("my teenager won't talk to me", "side by side"),
])
def test_round3_specific(q, must):
    o = compose(q, footer=False)
    assert must in o and not o.startswith(GEN), o[:150]


def test_cat_urinary_is_urgent_but_not_eating_keeps_old_answer():
    assert assess("แมวฉี่ไม่ออก นั่งเบ่ง")["risk_shown"] >= 70
    assert "ตับ" in compose("แมวไม่กินข้าวมา 2 วัน", footer=False)
