    lib = {name: d for name, _, d in TOPICS}
    main = lib.get(a["topics"][0]) if a["topics"] else GENERAL
    if a["topics"] and a["topics"][0] == "money" and "job" in a["topics"] and not MONEY_SHORT.search(text) \
            and not re.search(r"ซื้อ|ผ่อน|เก็บเงิน|ออม|โบนัส|เงินก้อน", text):
        main = lib["job"]                      # "อยากเปลี่ยนงาน แต่กลัวเงินเดือนลด" เป็นเรื่องงาน ไม่ใช่แผนเก็บเงิน
    elif a["topics"] and a["topics"][0] == "money" and _money_plan(text):
        main = MONEY_PLAN
    second = lib.get(a["topics"][1]) if len(a["topics"]) > 1 else None
    # เรื่องฉุกเฉิน/เปราะบาง: ขั้นของเรื่องนั้นต้องครบ ไม่แบ่งที่ให้หัวข้อรอง
    # (เดิม "กินยาเกินขนาด" เสียขั้นที่ 3 ให้ "ใช้สิทธิ์บัตรทอง")
    if a["topics"] and a["topics"][0] in _URGENT_TOPICS + ("adult_invite", "grief", "labor", "resign_block", "child_gaming", "consumer", "pet_hurt", "stranded", "teen_leave", "housing", "legal", "diagnosis",
                                                           "caregiver", "health_rights"):
        second = None
    if a["offer_flags"]:                 # ข้อเสนอที่มีโครงสร้างของการหลอก มาก่อนหัวข้ออื่น
        main, second = OFFER, None
    elif a["scam"] == ["lost"]:          # ถูกโกงไปแล้ว: ตามเงินคืนก่อน
        main, second = SCAM_LOST, None
    elif a["scam"] and set(a["scam"]) <= {"job", "lost"}:    # งานหลอก/ค้ามนุษย์
        main, second = SCAM_JOB_D, None
    elif a["scam"] and set(a["scam"]) <= {"romance", "lost"}:  # หลอกให้รัก/แอบอ้างเป็นเพื่อน
        main, second = SCAM_ROMANCE_D, None
    elif re.search(r"(?:เด็ก|คน|ป้า|ลุง|ผู้หญิง|ยาย)ข้างบ้าน[^\n]{0,12}?(?:โดน|ถูก)\S{0,6}?(?:ตี|ทำร้าย|ทุบ|ตบ|ทิ้ง|ขัง)", text):
        main, second = lib["witness"], None    # เดิมได้ "ความปลอดภัยของคุณมาก่อน" — ผู้ใช้เป็นคนได้ยิน ไม่ใช่ผู้ถูกทำร้าย
    elif _OTHER_HARM.search(text):
        main, second = OTHER_HARM, None        # "พี่สาวอยากฆ่าแฟน" เคยได้ "ขอบคุณที่พูดออกมาแทนที่จะทำ" เหมือนผู้ใช้เป็นคนโกรธเอง
    elif _FAMILY_WITNESS.search(text):
        # "พ่อเมาแล้วตีแม่ทุกคืน" เคยได้ "ความปลอดภัยของคุณมาก่อน · บาดเจ็บโทร 1669" — ผู้ใช้คือลูกที่เห็นเหตุการณ์
        main, second = FAMILY_WITNESS, None
    elif re.search(r"(?:ลูก|หลาน)[^\n]{0,8}?(?:โดน|ถูก)ครู[^\n]{0,8}?(?:ตี|ทำร้าย|ตบ|ลงโทษ|หยิก|ด่า)", text):
        # "ลูกโดนครูตี" เคยได้ "ความปลอดภัยของคุณมาก่อน · ออกไปอยู่ที่ที่มีคนอื่นแล้วโทร 191" — ผู้ใช้คือพ่อแม่ ไม่ใช่ผู้ถูกทำร้าย
        main, second = TEACHER_HARM, None
    elif a["relationship"] in ("collapse_risk", "critical"):   # ถูกทำร้าย/ควบคุม: ความปลอดภัยมาก่อน
        main, second = SAFETY, None
    elif a["disaster"]:                  # กำลังเจอภัย: ขั้นแรกของภัยนั้นมาก่อนทุกอย่าง
        main, second = {"open": [DISASTER_OPEN], "paths": a["disaster"]["steps"],
                        "ask": a["disaster"].get("ask") or DISASTER_ASK}, None
    elif set(a["topics"]) <= {"decision", "health", "family"}:
        # สัตว์เล็ก/เผาไร่/ทิ้งของเสีย — เดิมทางเลือกไปอยู่ท้ายคำตอบ ใต้ "เขียนสิ่งที่เกิดขึ้นเป็นประโยคเดียว" (รอบหาบั๊ก 8)
        try:
            _d = bridge_analyze(text)["data"]
        except Exception:
            _d = {}
        if (_d.get("disaster") or {}).get("after"):     # หลังน้ำลด — ขั้นหลังภัยเป็นทางหลัก ไม่ใช่ "เขียนเป็นประโยคเดียว"
            main, second = {"open": ["น้ำลดแล้วคือช่วงที่ต้องระวังอีกแบบ — ไฟ โรค และการขอความช่วยเหลือ"],
                            "paths": _d["disaster"]["steps"], "ask": "ตอนนี้ทุกคนในบ้านมีที่พักและน้ำสะอาดใช้แล้วหรือยัง?"}, None
        elif (_d.get("earth") or {}).get("steps"):
            e = _d["earth"]
            main, second = {"open": [f"เรื่อง{e['name']}มีทาง{'ที่ไม่ต้องทิ้งลงน้ำ' if e.get('kind') == 'water_dumping' else 'ที่ไม่ต้องเผา'} และหลายทางประหยัดกว่าด้วย" if e["self"]
                                     else "ควันหรือของเสียจากคนอื่นกระทบคุณได้ — ป้องกันตัวเองก่อน แล้วค่อยแจ้ง"],
                            "paths": e["steps"], "ask": "ทางไหนที่พอทำได้จริงในพื้นที่ของคุณ?"}, None
        elif (_d.get("animal") or {}).get("steps"):
            an = _d["animal"]
            main, second = {"open": ["สัตว์ป่วยมักซ่อนอาการ — ดูแลเร็วดีที่สุด" if an.get("sick")
                                     else "แก้ปัญหาได้โดยไม่ต้องฆ่า — และปลอดภัยกับคนในบ้านกว่า"],
                            "paths": an["steps"], "ask": "ตอนนี้ปัญหาหลักคืออะไร — เข้าบ้าน กัดของ หรือเรื่องสุขภาพ?"}, None

    paths = _paths(main, t)[:3]
    if second:
        extra = _pick(_paths(second, t)[:2], text, "2nd")
