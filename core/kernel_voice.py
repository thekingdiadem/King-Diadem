# ── ตัวเลือกที่ผู้ใช้พิมพ์มา (A. … / 1) … / "X หรือ Y") ─────────────
_OPT_LINE = re.compile(r"^\s*(?:[A-Ga-g]|[1-7])\s*[\.\)\:]\s*(.+?)\s*$", re.M)


def _options(text: str) -> list:
    opts = [o.strip() for o in _OPT_LINE.findall(text) if o.strip()]
    if len(opts) >= 2:
        return opts[:7]
    m = re.search(r"([^\n?？]{2,60}?)\s*หรือ\s*([^\n?？]{2,60}?)\s*(?:ดี|[?？]|$)", text)
    if m and "หรือว่า" not in m.group(0):
        a, b = m.group(1).strip(" ,"), m.group(2).strip(" ,")
        a = re.sub(r"^(ควร|จะ|ควรจะ)\s*", "", a)
        if a and b and a != b:
            return [a, b]
    return []


# ── จำนวนเงินในข้อความ: "2000 บาท", "2,000", "5 พัน", "1.5 หมื่น", "3k" ─
_UNITS = {"พัน": 1e3, "หมื่น": 1e4, "แสน": 1e5, "ล้าน": 1e6, "k": 1e3}
_MONEY = re.compile(r"(\d[\d,]*(?:\.\d+)?)\s*(พัน|หมื่น|แสน|ล้าน|k|K)?\s*(บาท|฿)?")


# เงินที่ลง/จ่าย/เสียไปแล้ว ไม่ใช่เงินที่เหลือใช้ ("ลงทุนไปแล้ว 2 แสน" เคยได้ "≈ 1,333 วัน")
_SPENT = re.compile(r"(?:ลงทุน|เสีย|จ่าย|ใช้|หมด|โดนโกง|ถูกโกง|โอน)\S{0,6}ไป|ขาดทุน")


def _money(text: str):
    best = None
    for m in _MONEY.finditer(text):
        num, unit, baht = m.group(1), (m.group(2) or "").lower(), m.group(3)
        if not (unit or baht):
            continue                         # ตัวเลขเฉยๆ (อายุ, เดือน) ไม่ใช่เงิน
        try:
            v = float(num.replace(",", "")) * _UNITS.get(unit, 1)
        except ValueError:
            continue
        if 0 < v < 1e12:
            best = v if best is None else best
    return best


