def assess(text: str, pattern: dict | None = None) -> dict:
    """ตัวเลขของระบบ (ไม่มี LLM): W, Risk, หัวข้อ, ความเร่งด่วน"""
    t = (text or "").lower()
    p = pattern if isinstance(pattern, dict) else {}
    E = max(0.0, min(100.0, _num(p.get("entropy"), 40)))
    R = max(0.0, min(100.0, _num(p.get("resource"), 50)))
    S = max(0.0, min(100.0, _num(p.get("stability"), 60)))
    W = ((100 - E) + R + S) / 3
    risk = 0.5 * E + 0.5 * (100 - R)

    tr = {}
    try:
        from ENGINE.risk_engine import evaluate_risk
        tr = evaluate_risk(text) or {}
    except Exception:
        pass
    crisis = bool(tr.get("self_harm")) or _hit(t, CRISIS_PHRASES)
    topics = [name for name, phrases, _ in TOPICS if _hit(t, phrases)]
    if tr.get("basic_needs") and "basic" not in topics:
        topics.insert(0, "basic")
    text_risk = {"critical": 90, "high": 75, "medium": 55}.get(str(tr.get("level")), 0)
    if crisis:
        text_risk = max(text_risk, 95)
    if any(x in topics for x in ("violence", "health_emergency")):
        text_risk = max(text_risk, 85)
    if "basic" in topics:
        text_risk = max(text_risk, 75)
        W = min(W, 30)
    if crisis:
        W = min(W, 20)
    # โครงสร้างของข้อเสนอ (การันตี + เร่ง + ชวนผ่านคนรู้จัก) — แยกจากอารมณ์ผู้ใช้
    flags = offer_red_flags(text)
    text_risk = max(text_risk, offer_risk(flags))
    return {
        "W": round(W), "risk": round(max(risk, text_risk)),
        # risk จากข้อความล้วน (0 = ไม่มีสัญญาณ) — ใช้ยกค่า risk_score ที่ engine คิดจากสถานะอย่างเดียว
        "text_risk": round(text_risk), "offer_flags": flags,
        "crisis": crisis, "topics": topics, "money": _money(text),
        "options": _options(text or ""),
    }


