def _num(v, d: float) -> float:
    try:
        x = float(v)
    except (TypeError, ValueError):
        return d
    return x if x == x and abs(x) != float("inf") else d


def _hit(text: str, phrases) -> bool:
    """คำอังกฤษต้องตรงทั้งคำ — คำไทยเป็นวลีเต็ม (ไม่มีช่องว่างระหว่างคำ จึงใช้วลีที่ยาวพอ)"""
    for p in phrases:
        if isinstance(p, re.Pattern):          # วลีไทยที่ต้องตัดบริบทผิดออก เช่น ไอ ≠ ไอเดีย
            if p.search(text):
                return True
        elif p.isascii():
            if re.search(r"(?<![a-z])" + re.escape(p) + r"(?![a-z])", text):
                return True
        elif p in text:
            return True
    return False


def _paths(d: dict, t: str) -> list:
    """ทางของหัวข้อ — รายการที่เป็น (วลี, ข้อความ) ใช้เฉพาะเมื่อข้อความมีวลีนั้น"""
    out = []
    for p in d["paths"]:
        if isinstance(p, tuple):
            if _hit(t, p[0]):
                out.append(p[1])
        else:
            out.append(p)
    return out


def _pick(seq, text: str, salt: str = ""):
    """เลือกแบบคงที่จาก hash ของข้อความ — ไม่สุ่ม แต่ข้อความต่างกันได้ถ้อยคำต่างกัน"""
    if not seq:
        return None
    h = int(hashlib.sha256((salt + "|" + text).encode("utf-8")).hexdigest()[:8], 16)
    return seq[h % len(seq)]


