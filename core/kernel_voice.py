_DEBT_HARASS_RISK = 55


def assess(text: str, pattern: dict | None = None) -> dict:
    """ตัวเลขของระบบ (ไม่มี LLM): W, Risk, หัวข้อ, ความเร่งด่วน"""
    t = (text or "").lower()
    p = pattern if isinstance(pattern, dict) else {}
    E = max(0.0, min(100.0, _num(p.get("entropy"), 40)))
    R = max(0.0, min(100.0, _num(p.get("resource"), 50)))
    S = max(0.0, min(100.0, _num(p.get("stability"), 60)))
    W = ((100 - E) + R + S) / 3
    risk = 0.5 * E + 0.5 * (100 - R)

    tr = {}
    try:
        from ENGINE.risk_engine import evaluate_risk
        tr = evaluate_risk(text) or {}
    except Exception:
        pass
    # "เพื่อนบอกว่าอยากตาย" → ผู้ใช้กำลังช่วยคนอื่น: วิกฤตของผู้ใช้ดูจากส่วนที่เหลือของข้อความ
    own = strip_third_party(t) if THIRD_PARTY_CRISIS.search(t) else t
    crisis = bool(tr.get("self_harm")) or _hit(own, CRISIS_PHRASES)
    topics = [name for name, phrases, _ in TOPICS if _hit(own if name in _OWN_ONLY else t, phrases)]
    if tr.get("basic_needs") and "basic" not in topics:
        topics.insert(0, "basic")
    elif "basic" in topics:                    # ขาดปัจจัยพื้นฐาน มาก่อนเรื่องเงินทั่วไป
        topics.insert(0, topics.pop(topics.index("basic")))
    text_risk = {"critical": 90, "high": 75, "medium": 55}.get(str(tr.get("level")), 0)
    if crisis:
        text_risk = max(text_risk, 95)
    if any(x in topics for x in ("violence", "health_emergency", "overdose", "sexual_abuse", "someone")):
        text_risk = max(text_risk, 90 if "someone" in topics else 85)
    for name, lvl in _TOPIC_RISK.items():
        if name in topics:
            text_risk = max(text_risk, lvl)
    # ตั้งครรภ์อายุต่ำกว่า 15 — ต้องมีผู้ใหญ่ช่วยและอาจเป็นการถูกล่วงละเมิด (รอบหาบั๊ก 6)
    if "pregnancy" in topics and re.search(r"อายุ\s*(?:1[0-4]|[89])(?!\d)|(?<!\d)(?:1[0-4]|[89])\s*(?:ขวบ|ปี)(?!\d)|\b(?:1[0-4]|[89]) ?(?:yo|years? old)\b", t):
        text_risk = max(text_risk, 65)
    # ปืนในบ้าน: เล่าเฉยๆ ไม่ตื่นตูม (50) — แต่ไม่รู้ของใคร/กลัว/ขู่/เมา หรือมีความคิดทำร้าย = อันตรายจริง (85)
    if "weapon" in topics:
        danger = WEAPON_DANGER.search(t) or text_risk >= 65 or set(topics) & {"harm_others", "violence", "warning"}
        text_risk = max(text_risk, 85 if danger else 50)
    if GAMBLING_LOSS.search(t):                # พนันจนหมดตัว/เป็นหนี้ — มักลามเป็นหนี้นอกระบบและความคิดทำร้ายตัวเอง
        text_risk = max(text_risk, 60)
        if "addiction" not in topics:
            topics.append("addiction")
    if DEBT_HARASS.search(t):                  # ทวงหนี้ขู่/ประจาน — ผิดกฎหมายและกดดันหนัก
        text_risk = max(text_risk, _DEBT_HARASS_RISK)
    # มิจฉาชีพ (แอบอ้าง/ลิงก์/โอนเงิน) — เลือกจากโครงสร้าง ไม่ใช่คำเดี่ยว
    scam = scam_flags(text)
    if scam:
        topics = ["scam"] + [x for x in topics if x != "scam"]
        text_risk = max(text_risk, 75 if set(scam) & {"impersonation", "story", "job", "romance"} else 60)
    if "warning" in topics and not crisis:
        text_risk = max(text_risk, 65)
    if "help" in topics:
        text_risk = max(text_risk, 50)
    if "basic" in topics:
        text_risk = max(text_risk, 75)
        W = min(W, 30)
    if crisis:
        W = min(W, 20)
    # โครงสร้างของข้อเสนอ (การันตี + เร่ง + ชวนผ่านคนรู้จัก) — แยกจากอารมณ์ผู้ใช้
    flags = offer_red_flags(text)
    text_risk = max(text_risk, offer_risk(flags))
    # ความรุนแรง/การควบคุมในความสัมพันธ์ (ENGINE/relationship_engine ผ่าน core/engine_bridge)
    rel = None
    try:
        from core.engine_bridge import _relationship
        rel = _relationship(text)
    except Exception:
        pass
    if rel:
        text_risk = max(text_risk, rel["data"]["risk_score"])
    # ภัยที่กำลังเจอ (DOMAINS/survival_engine ผ่าน core/engine_bridge) — เดิม "น้ำท่วมบ้าน" ได้ Risk 0
    dis = None
    try:
        from core.engine_bridge import _disaster
        dis = _disaster(text)
    except Exception:
        pass
    if dis and dis["data"]["active"]:
        text_risk = max(text_risk, dis["data"]["threat"])
    return {
        "scam": scam,
        "W": round(W), "risk": round(max(risk, text_risk)),
        # ตัวเลขที่โชว์ในคำตอบ: ยังไม่รู้สถานะจริงของผู้ใช้ → W "—" และ Risk จากข้อความล้วน
        # (เดิมโชว์ "W 57 · Risk 45" จากค่าตั้งต้น ขณะที่แถบใต้คำตอบโชว์ "W — · Risk 0" — สองตัวเลขขัดกัน)
        "W_shown": round(W) if p else "—", "risk_shown": round(max(risk, text_risk)) if p else round(text_risk),
        # risk จากข้อความล้วน (0 = ไม่มีสัญญาณ) — ใช้ยกค่า risk_score ที่ engine คิดจากสถานะอย่างเดียว
        "text_risk": round(text_risk), "offer_flags": flags,
        "relationship": rel["data"]["status"] if rel else None,
        "disaster": dis["data"] if dis and dis["data"]["active"] else None,
        "crisis": crisis, "topics": topics, "money": _money(text),
        "options": _options(text or ""),
    }


