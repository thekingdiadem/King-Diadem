def compose_asia(lang: str, kind: str, status: str, sign: str, footer: bool = True) -> str | None:
    """คำตอบเรื่องด่วนในภาษานั้น — ไม่มีภาษาหรือชนิดนี้คืน None ให้ใช้ทางเดิม"""
    r = REPLY.get(lang, {}).get(kind)
    if not r:
        return None
    opener, steps, ask = r
    body = "\n".join(f"{i + 1}) {s}" for i, s in enumerate(steps))
    tag = "\n· Answered from the system's equations — no AI used" if footer else ""
    return f"{opener}\n\n{status}\n\n{body}\n\n{ask}\n\n{sign}" + tag
