import re

# ── เดาภาษา: อักษรเฉพาะก่อน แล้วค่อยดูคำของภาษาที่ใช้อักษรละติน ─────────────
_SCRIPT = (("my", r"[က-႟]"), ("km", r"[ក-៿]"), ("lo", r"[຀-໿]"),
           ("si", r"[඀-෿]"), ("ta", r"[஀-௿]"), ("bn", r"[ঀ-৿]"))
_SCRIPT_RX = [(c, re.compile(r)) for c, r in _SCRIPT]
_DEVANAGARI = re.compile(r"[ऀ-ॿ]")
_NEPALI = re.compile(r"मलाई|छैन|हुनुहुन्छ|गर्नु|भयो|सक्दैन|छु\b|छ\b|कुट्छ|मर्न|बचाउ(?!ो)")
_ARABIC = re.compile(r"[؀-ۿ]")
_URDU = re.compile(r"[ےۓٹڈڑںہھ]")
_PERSIAN = re.compile(r"[پچژگ\u200c]|شوهرم|مادرم|پدرم|منو|خوام|می‌?خواهم|میخوام|نمی‌?|است\b|کمک")
_VI = re.compile(r"[ăđơưạảấầẩẫậắằẳẵặẹẻẽếềểễệỉịọỏốồổỗộớờởỡợụủứừửữựỳỵỷỹ]", re.I)
