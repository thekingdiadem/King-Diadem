_MS = re.compile(r"\b(?:nak|tak|awak|bernafas|boleh|pukul\s+saya)\b", re.I)
_ID = re.compile(r"\b(?:aku|tidak|bisa|bernapas|ingin|mau|suamiku|ibuku|istriku|tolong)\b", re.I)


def asia_lang(text) -> str | None:
    """ภาษาเอเชียที่มีคำตอบสำเร็จรูปในไฟล์นี้ — ไม่ใช่ภาษาเหล่านี้คืน None"""
    t = str(text or "")
    for code, rx in _SCRIPT_RX:
        if rx.search(t):
            return code
    if _DEVANAGARI.search(t):
        return "ne" if _NEPALI.search(t) else "hi"
    if _ARABIC.search(t):
        if _URDU.search(t):
            return "ur"
        return "fa" if _PERSIAN.search(t) else "ar"
    if _VI.search(t):
        return "vi"
    if _TR.search(t):
        return "tr"
    if _TL.search(t):
        return "tl"
    if _MS.search(t) and not re.search(r"\b(?:aku|tidak|bisa|bernapas)\b", t, re.I):
        return "ms"
    if _ID.search(t):
        return "id"
    return None


