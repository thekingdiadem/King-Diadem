# ตัวเลขที่ต้องลงทะเบียน: มีหน่วย (เวลา เงิน สัดส่วน อายุ จำนวนครั้ง)
UNIT = r"(?:%|ชั่วโมง|ชม\.?|นาที|วัน|เดือน|ปี|บาท|เท่า|baht|hours?|minutes?|days?|months?|years?|ครั้ง)"
NUMBER = re.compile(r"\d[\d,.]*(?:\s?–\s?\d+)?\s?" + UNIT)
# เบอร์โทร: รูปแบบยาวก่อน แล้วเลขสั้น 3–5 หลักที่ไม่ใช่ตัวเลขมีหน่วย/ค่าความดัน (180/120)
PHONE = re.compile(r"(?<![\d/.,–-])(?:(1-8\d\d-(?:\d{3}-\d{4}|[A-Z]+(?:-[A-Z]+)?)|0[38]0\d \d{3,4} \d{3,4}|116 123|13 11 14|\d{3}-\d{3})(?![\dA-Z])"
                   r"|(\d{3,5})(?![\d/,.%–-]|\s?" + UNIT + r"))")


def answer_text(entry) -> str:
    _n, _rx, _r, _u, th, en = entry
    return " ".join([th[0], *th[1], th[2], en[0], *en[1], en[2]])


def phones(text: str) -> set:
    return {a or b for a, b in PHONE.findall(text)}


def numbers(text: str) -> set:
    return {m.strip() for m in NUMBER.findall(text)}


