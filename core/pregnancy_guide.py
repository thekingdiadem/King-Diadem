CARE_RX = re.compile(r"^(?=[\s\S]*(?:" + PREG + r"))(?=[\s\S]*(?:" + CARE + r"))", re.I)
ALONE_RX = re.compile(r"^(?=[\s\S]*(?:" + PREG + r"))(?=[\s\S]*(?:" + ALONE + r"))", re.I)


def is_pregnant(text) -> bool:
    return bool(_PREG.search(str(text or "")))


def dangers(text) -> list:
    """สัญญาณอันตรายที่เจอ (เรียงตามความด่วน) — ต้องเป็นข้อความเรื่องตั้งครรภ์ก่อน"""
    t = str(text or "")
    if not _PREG.search(t):
        return []
    return [k for k in DANGER if _DANGER[k].search(t)]


def alone(text) -> bool:
    t = str(text or "")
    return bool(_PREG.search(t) and _ALONE.search(t))


