"""
core/thai_signals.py — วลีไทยที่ต้องดูบริบท (ใช้ร่วมกันทุก engine)

ภาษาไทยไม่มีช่องว่างระหว่างคำ วลีสั้นจึงไปตรงกับประโยคที่ความหมายต่าง:
- "ไม่อยากอยู่แล้ว" = สัญญาณทำร้ายตัวเอง  แต่ "ไม่อยากอยู่แล้วที่ทำงานนี้" = อยากลาออก
- "ไม่มีเงิน" = ขาดปัจจัย  แต่ "ไม่มีเงินซื้อไอโฟน" ไม่ใช่เรื่องเอาตัวรอด

lookahead วางไว้ "หลัง อยู่" ครอบ แล้ว/ต่อ ที่ไม่บังคับ — ถ้าวางหลังกลุ่มที่ไม่บังคับ regex จะ
ถอยกลับไปจับ "ไม่อยากอยู่" แล้วผ่าน lookahead ได้เสมอ
"""
import re

# ไม่อยากอยู่ (แล้ว/ต่อ) — ยกเว้นเมื่อตามด้วยสถานที่/คน/สภาพ (ไม่ใช่ "ไม่อยากมีชีวิต")
NOT_WANT_TO_LIVE = re.compile(
    r"ไม่อยากอยู่(?!(?:แล้ว|ต่อ)?\s*(?:ที่|กับ|บ้าน|บริษัท|ห้อง|หอ|คอนโด|ตรงนี้|ทีม|งาน|ใน|แถว|เมือง|"
    r"ประเทศ|กรุงเทพ|ต่างจังหวัด|คนเดียว|เฉย|นิ่ง|เป็น|ใกล้|ข้าง|หน้า|เวร|ดึก|โรงเรียน|มหาลัย))"
    r"(?:แล้ว|ต่อ)?"
)

# ไม่มีเงิน — ยกเว้นเมื่อเป็นของที่ไม่จำเป็นต่อการอยู่รอด
NO_MONEY_ESSENTIAL = re.compile(
    r"ไม่มีเงิน(?!\s*(?:ซื้อ(?!\s*(?:ข้าว|อาหาร|ยา|นม|น้ำ|กับข้าว|ของกิน|แพมเพิส))|เที่ยว|ไปเที่ยว|"
    r"ดูหนัง|ดูคอน|เติมเกม|แต่งรถ|ช้อป|เปลี่ยนมือถือ|ดาวน์รถ|"
    # "ยังไม่มีเงินเก็บ" = ไม่มีเงินออม ไม่ใช่ไม่มีเงินซื้อข้าว (เคยได้เส้นทาง survival Risk 55)
    r"เก็บ|ออม|สำรอง|ก้อน|ลงทุน|ดาวน์|เปิดร้าน|เรียนต่อ))"
)


def has(text: str, phrase) -> bool:
    """phrase เป็น str (substring) หรือ compiled regex"""
    if isinstance(phrase, re.Pattern):
        return phrase.search(text) is not None
    return phrase in text


def label(phrase) -> str:
    return phrase.pattern[:24] if isinstance(phrase, re.Pattern) else phrase


# ── คำสั้นที่ซ้อนอยู่ในคำอื่น ──────────────────────────────────────
# ท้อ(แท้/ใจ) ≠ ท้อง (ปวดท้อง ตั้งท้อง ท้องเสีย)
DISCOURAGED = re.compile(r"ท้อ(?!ง)")
