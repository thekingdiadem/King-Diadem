def small_talk(text) -> str | None:
    t = str(text or "").strip()
    if len(t) > 24:
        return None
    for name, rx in SMALL_TALK.items():
        if rx.search(t):
            return name
    return None


def third_party_crisis(text) -> bool:
    return bool(THIRD_PARTY_CRISIS.search(str(text or "")))


# คำพูดของคนอื่นแบบ "เพื่อนบอกว่า …" — ทั้งประโยคที่ตามมาเป็นเรื่องของเขา จนกว่าผู้ใช้จะพูดถึงตัวเอง
# (ทดสอบ 10,000 ครั้ง: "เพื่อนบอกว่าคิดสั้น" "เพื่อนบอกว่ากรีดแขน" เคยนับเป็นวิกฤตของผู้ใช้)
REPORTED_SPEECH = re.compile(
    _OTHERS + r"\S{0,12}?(?:บอก|พูด|โพสต์|พิมพ์|ส่งข้อความ|ทักมา|ไลน์มา|เขียน|ขู่)(?:มา)?\S{0,4}?ว่า\s*"
    # ประโยคที่มีสรรพนามของผู้ใช้ ("พี่บอกว่าถ้าฉันอยากตายให้โทรหา") หยุดตรงนั้น — ส่วนที่เหลือเป็นเรื่องของผู้ใช้
    # ยกเว้นคำบอกลาที่คนนั้นพูดถึงตัวเอง: "เพื่อนบอกว่าพรุ่งนี้คงไม่มีฉันแล้ว" (ฉัน = เพื่อน ไม่ใช่ผู้ใช้)
    r"((?:[^\n.!?]{0,12}?(?:คง|จะ)?ไม่มี(?:ฉัน|หนู|ผม|เรา|กู)(?:อยู่)?(?:แล้ว|อีกแล้ว|บนโลกนี้)|(?:(?!ฉัน|หนู|ผม|เรา|กู|ตัวเอง)[^\n.!?]))+)")


def reported_clauses(text) -> list:
    """ประโยคที่ผู้ใช้ยกคำพูดของคนอื่นมาเล่า"""
    return [m.group(1) for m in REPORTED_SPEECH.finditer(str(text or ""))]


def strip_third_party(text) -> str:
    """ตัดส่วนที่เล่าถึงวิกฤตของคนอื่นออก — เหลือเฉพาะสิ่งที่ผู้ใช้พูดถึงตัวเอง
    ("เพื่อนบอกว่าอยากตาย แล้วฉันก็อยากตายเหมือนกัน" ยังจับวิกฤตของผู้ใช้ได้)"""
    return REPORTED_SPEECH.sub(" ", THIRD_PARTY_CRISIS.sub(" ", str(text or "")))


_LATIN_THAI = re.compile(r"(?<=[A-Za-z])(?=[\u0E00-\u0E7F])|(?<=[\u0E00-\u0E7F])(?=[A-Za-z])")


def normalize_mixed(text) -> str:
    """เว้นวรรคระหว่างอังกฤษกับไทยที่พิมพ์ติดกัน — "I want to dieค่ะ" เคยหลุดเพราะ \\b ไม่ตัดคำตรงนั้น"""
    return _LATIN_THAI.sub(" ", str(text or ""))


# ผู้ใช้เล่าว่า "ตัวเอง" เคยทำร้าย/พูดไม่ดีใส่คนอื่น แล้วรู้สึกผิดหรือเลิกแล้ว — ไม่ใช่คนที่กำลังถูกทำร้าย
# (ข้อความจริง: "ทุกคนที่พี่เกิดมาเคยทำร้ายเขา … แต่ว่าตอนนี้ไม่มีแล้วนะ" เคยได้หัวข้อความรุนแรง Risk 100)
# ต้องมีครบสองอย่าง: ผู้ใช้เป็นคนทำ (สรรพนามของผู้ใช้อยู่ก่อน "เคย") + ขอโทษ/รู้สึกผิด/เลิกแล้ว
# "ตอนนี้ไม่มีที่ไปแล้ว" ไม่นับว่าเลิกแล้ว — ต้องเป็น "ไม่มีแล้ว" "ไม่ทำแล้ว" ติดกัน
OWN_PAST_HARM = re.compile(
    r"(?<!โดน)(?<!ถูก)(?:ฉัน|ผม|พี่|หนู|เรา|กู|ตัวเอง)(?:ที่)?(?:(?!โดน|ถูก|เขา|มัน|พ่อ|แม่|แฟน|ผัว|เมีย)\S){0,10}?เคย\S{0,6}?"
    r"(?:ทำร้าย|ตี|ตบ|ทุบ|เตะ|ผลัก|ด่า|พูด(?:จา)?ไม่ดี|ทำไม่ดี)(?!ตัวเอง)\S{0,10}")
OWN_HARM_REMORSE = re.compile(
    r"ขอโทษ|รู้สึกผิด|ละอาย|เสียใจที่|สำนึก|(?:ตอนนี้|เดี๋ยวนี้|ปัจจุบัน)\S{0,6}?ไม่(?:มี|ทำ|เป็น)(?:แบบนั้น|อย่างนั้น)?(?:อีก)?แล้ว|"
    r"เลิก(?:ทำ)?(?:แบบนั้น|อย่างนั้น)?แล้ว|ไม่ทำ(?:แบบนั้น|อย่างนั้น)?อีกแล้ว")


def strip_own_past_harm(text) -> str:
    """ตัดส่วนที่ผู้ใช้สารภาพว่าเคยทำร้ายคนอื่น (เมื่อรู้สึกผิด/เลิกแล้ว) ออก ก่อนดูว่าผู้ใช้กำลังถูกทำร้ายไหม"""
    s = str(text or "")
    if not OWN_HARM_REMORSE.search(s):
        return s
    return OWN_PAST_HARM.sub(" ", s)


