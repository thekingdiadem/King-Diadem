BREAKUP = re.compile(r"บอกเลิก|เลิกกัน|เลิกรา|ขอเลิก|(?:ถูก|โดน)\S{0,8}?ทิ้ง|แฟนทิ้ง|ทิ้ง(?:ฉัน|เรา|ผม|หนู|กัน)")
# แฟน (คนรัก) — ไม่ใช่ แฟนบอล แฟนคลับ แฟนเพจ แฟนตาซี
PARTNER = re.compile(r"แฟน(?!บอล|คลับ|เพจ|ไซต์|ตาซี|ซี|ๆ|เมด|ชั่น)")
# พ่อ/แม่ (คน) — ไม่ใช่ พ่อค้า แม่ค้า แม่น้ำ แม่บ้าน แม่นยำ ฯลฯ
PARENT = re.compile(r"พ่อ(?!ค้า|ครัว|มด|บ้าน|พิมพ์)|แม่(?!น้ำ|ค้า|ครัว|บ้าน|ทัพ|เหล็ก|น|ไม้|ลาย|กุญแจ|พิมพ์|ข่าย|เบี้ย|ชี|ส่วน|แบบ|มด|ปู)")
# หมอ (แพทย์) — ไม่ใช่ หมอก หมอน หมอลำ หมอดู  ("หมอนัด" = หมอ + นัด)
DOCTOR = re.compile(r"หมอ(?!ก|ลำ|ดู|น(?!ัด))")


# ── ข้อเสนอเงิน/ลงทุนที่มีโครงสร้างของการหลอก ───────────────────────────
# ดู "โครงสร้างของข้อเสนอ" แยกจากอารมณ์ผู้ใช้: คนตื่นเต้นกับข้อเสนอที่การันตีผลตอบแทน
# + เร่งให้ตอบ = ต้องชะลอ ไม่ใช่ร่วมดีใจ (แชร์ลูกโซ่/หลอกลงทุนใช้สูตรนี้)
OFFER_MONEY = re.compile(
    r"ลงทุน|ลงหุ้น|ร่วมหุ้น|ถือหุ้น|ร่วมทุน|ลงเงิน|ลงขัน|โอนเงิน|ฝากเงิน|ปันผล|ผลตอบแทน|"
    r"เทรด|คริปโต|ฟอเร็กซ์|forex|ออมทอง|invest|แชร์ลูกโซ่|เล่นแชร์|วงแชร์|ลงแชร์"
)
# "ไม่แน่นอน" / "ไม่ชัวร์" = ไม่แน่ใจ (ตรงข้ามกับการการันตี)
OFFER_GUARANTEE = re.compile(
    r"(?<!ไม่)แน่นอน|(?<!ไม่)ชัวร์|การันตี|รับประกัน|ไม่มี(?:ทาง)?ขาดทุน|ไม่ขาดทุนแน่|ไม่เสี่ยงเลย|"
    r"ความเสี่ยงเป็นศูนย์|คืนทุน(?:ใน|ภายใน)?\s*\d+\s*(?:วัน|สัปดาห์|อาทิตย์|เดือน)|"
    r"(?:ปันผล|ผลตอบแทน|กำไร)\s*\d+(?:\.\d+)?\s*%\s*(?:ต่อ|/)\s*(?:วัน|สัปดาห์|อาทิตย์|เดือน)|"
    # "กำไรวันละ 5%" — ลำดับคำกลับ เคยไม่ติด (รอบหาบั๊ก 21)
    r"(?:ปันผล|ผลตอบแทน|กำไร)\s*(?:วันละ|สัปดาห์ละ|อาทิตย์ละ|เดือนละ)\s*\d+(?:\.\d+)?\s*%|"
    # "ได้ดอก 20 ต่อเดือน" (ไม่มี %) — ดอกเบี้ยเงินกู้ไม่ติดเพราะต้องมีตัวเลขต่อจาก "ดอก" ทันที
    r"(?:ได้|ให้)(?:ดอก|ปันผล|ผลตอบแทน|กำไร)\s*\d+(?:\.\d+)?\s*%?\s*(?:ต่อ|/)\s*(?:วัน|สัปดาห์|อาทิตย์|เดือน)|"
    # "ชวนลงทุนคริปโต ได้ 30% ต่อเดือน" เคยไม่ติด (ไม่มีคำว่าผลตอบแทน/กำไร) — ได้คำแนะนำทำธุรกิจ Risk 0
    r"ได้\s*\d+(?:\.\d+)?\s*%\s*(?:ต่อ|/)\s*(?:วัน|สัปดาห์|อาทิตย์|เดือน)|ได้(?:วันละ|สัปดาห์ละ|อาทิตย์ละ|เดือนละ)\s*\d+(?:\.\d+)?\s*%|"
    r"\d+(?:\.\d+)?\s*%\s*(?:a|per|every)\s*(?:day|week|month)\b|"
    r"guaranteed?|risk[- ]free"
)
OFFER_URGENCY = re.compile(
    r"ต้องตอบ\S{0,6}(?:พรุ่งนี้|วันนี้|คืนนี้)|ตอบ(?:ภายใน)?(?:พรุ่งนี้|วันนี้|คืนนี้)|ภายในวันนี้|"
    r"วันนี้เท่านั้น|หมดเขต|รีบ(?:โอน|ตัดสินใจ|ลง|จอง)|โอกาสสุดท้าย|ที่นั่งจำกัด|รับจำนวนจำกัด|ด่วน"
)
OFFER_RECRUIT = re.compile(r"ชวน(?:ลง|มา|เข้า|ร่วม|ทำ)|หาคน(?:มา)?(?:ลง|ร่วม)|ดาวน์ไลน์|ลูกทีม|แนะนำเพื่อน")

OFFER_FLAG_TH = {"guarantee": "การันตีผลตอบแทน/คืนทุนเร็ว", "urgency": "เร่งให้ตัดสินใจ",
                 "recruit": "ชวนลงเงินผ่านคนรู้จัก"}


def offer_red_flags(text) -> list:
    """สัญญาณในข้อเสนอ (ไม่ใช่ในอารมณ์): guarantee / urgency / recruit
    ต้องมีบริบทเงิน-ลงทุน และมีการการันตี หรือมีอย่างน้อย 2 สัญญาณ"""
    t = str(text or "").lower()
    if not OFFER_MONEY.search(t):
        return []
    flags = [name for name, rx in (("guarantee", OFFER_GUARANTEE), ("urgency", OFFER_URGENCY),
                                   ("recruit", OFFER_RECRUIT)) if rx.search(t)]
    return flags if ("guarantee" in flags or len(flags) >= 2) else []


def offer_risk(flags) -> int:
    """Risk จากโครงสร้างข้อเสนอ: การันตี 65 · +เร่ง 75 · +ชวนผ่านคนรู้จัก 80 · เร่ง+ชวน 60"""
    f = set(flags or ())
    if not f:
        return 0
    if "guarantee" in f:
        return 65 + (10 if "urgency" in f else 0) + (5 if "recruit" in f else 0)
    return 60


