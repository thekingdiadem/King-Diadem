def strip_own_past_harm(text) -> str:
    """ตัดส่วนที่ผู้ใช้สารภาพว่าเคยทำร้ายคนอื่น (เมื่อรู้สึกผิด/เลิกแล้ว) ออก ก่อนดูว่าผู้ใช้กำลังถูกทำร้ายไหม"""
    s = str(text or "")
    if not OWN_HARM_REMORSE.search(s):
        return s
    return OWN_PAST_HARM.sub(" ", s)


