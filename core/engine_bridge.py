# สำนวน/เปรียบเทียบ — "น้ำท่วมปอด" (ดีใจล้น) "ใจเหมือนแผ่นดินไหว" "ไฟป่าในใจ" เคยได้ขั้นตอนหนีภัยและ Risk 53–64
_HAZARD_IDIOM = re.compile(r"น้ำท่วมปอด|น้ำท่วมหัวเอาตัวไม่รอด|(?:เหมือน|ดั่ง|ดุจ|ราวกับ|ยังกับ)\S{0,8}$")
_HAZARD_HEART = re.compile(r"^\S{0,4}(?:ใน|กลาง)(?:หัว)?(?:ใจ|อก)")


def _disaster(text: str) -> dict | None:
    hit = None
    for h in _HAZARDS:
        for mm in h[3].finditer(text):
            before, after = text[max(0, mm.start() - 12):mm.start()], text[mm.end():mm.end() + 10]
            idiom = _HAZARD_IDIOM.search(text[max(0, mm.start() - 4):mm.end() + 24])
            if (idiom and idiom.group(0).startswith("น้ำท่วม")) or _HAZARD_IDIOM.search(before) or _HAZARD_HEART.search(after):
                continue
            hit = h
            break
        if hit:
            break
    if not hit:
        return None
    kind, event, name, _, steps = hit
    place, ask = None, None
    if kind in _HAZARD_PLACES:
        q = _hazard_place(kind, text)
        if q:
            place, steps = q[1], q[3]
        else:
            ask = _HAZARD_PLACES[kind][1]               # ยังไม่รู้ว่าอยู่ที่ไหน — ให้ขั้นทั่วไปแล้วถาม
    far = bool(_HAZARD_FAR.search(text)) and not _HAZARD_NEAR.search(text)
    # บอกที่ที่ตัวเองอยู่ตอนเกิดภัย ("ติดในลิฟต์" "อยู่ภูเก็ต แผ่นดินไหวแรงมาก") = กำลังเจออยู่จริง
    severity = 25 if far else 85 if (_HAZARD_NEAR.search(text) or place) else 60
    try:
        from DOMAINS.survival_engine import analyze_global_event
        r = analyze_global_event(event_type=event, severity=severity)
        threat, level = float(r.get("threat_score") or 0), str(r.get("threat_level") or "")
    except Exception:  # pragma: no cover
        threat, level = 0.0, ""
    hotline = ("เบอร์ที่ใช้ได้: 1784 (ปภ. สายด่วนนิรภัย) · 1669 (เจ็บป่วยฉุกเฉิน) · 191 (ตำรวจ)"
               + (" · 199 (ดับเพลิง)" if kind == "fire" else ""))
    if far:
        lines = [f"แผนเตรียมรับ{name} — รู้ไว้ก่อนว่าถ้าเกิดจริงต้องทำอะไรก่อน: {steps[0]}", hotline]
    else:
        lv = _HAZARD_LEVEL_TH.get(level, "")
        lines = ([f"ภัยที่กำลังเจอ: {name}" + (f" · {place}" if place else "") + (f" · ระดับภัย {lv}" if lv else "")]
                 + steps + [hotline])
    return {"lines": lines, "data": {"kind": kind, "name": name, "active": not far,
                                     "threat": round(threat), "steps": steps, "place": place, "ask": ask}}


# ── 6. คิดเลขที่ผู้ใช้ถาม (ENGINE/tool_executor) ─────────────────────────
# ต้องมีทั้งนิพจน์ (ตัวเลข เครื่องหมาย ตัวเลข) และคำถามหาผล — "24/7" "1-2 วัน" "50/50" ไม่ใช่โจทย์
# ลบต้องมีช่องว่างทั้งสองข้าง ("25000 - 18000") — "1-2 วัน" เป็นช่วง ไม่ใช่โจทย์
_CALC_EXPR = re.compile(r"(?<![\d/.])\d[\d,]*(?:\.\d+)?(?:(?:\s*[+×x*÷]\s*|\s+-\s+)\d[\d,]*(?:\.\d+)?)+(?![\d/])")
_CALC_ASK = re.compile(r"เท่าไหร่|เท่าไร|เท่าใด|ได้เท่า|ทั้งหมดกี่|รวมกี่|คิดยังไง|ช่วยคิด|ช่วยคำนวณ|คำนวณ|=\s*\?|=\s*$|how much", re.I)


def _fmt(v: float) -> str:
    return f"{v:,.0f}" if abs(v - round(v)) < 1e-9 else f"{v:,.2f}"


def _calc(text: str) -> dict | None:
    if not _CALC_ASK.search(text):
        return None
    try:
        from ENGINE.tool_executor import _safe_calc
    except Exception:  # pragma: no cover
        return None
    lines, results = [], []
    for m in list(_CALC_EXPR.finditer(text))[:3]:
        raw = m.group(0)
        expr = raw.replace(",", "").replace("×", "*").replace("x", "*").replace("÷", "/")
        r = _safe_calc(expr)
        if "result" not in r:
            continue
        shown = re.sub(r"\s*([+×x*÷-])\s*", lambda o: " " + {"x": "×", "*": "×", "÷": "÷"}.get(o.group(1), o.group(1)) + " ", raw)
        lines.append(f"คิดเลข: {shown.strip()} = {_fmt(float(r['result']))}")
        results.append(r["result"])
    return {"lines": lines, "data": {"results": results}} if lines else None


